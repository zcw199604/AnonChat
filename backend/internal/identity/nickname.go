// GenerateNickname 生成形如“迷路的水獭”的随机昵称：形容词 + “的” + 名词，不含任何编号。
func GenerateNickname() string {
	adj := adjectives[randIntN(len(adjectives))]
	noun := nouns[randIntN(len(nouns))]
	return adj + "的" + noun
}

// GeneratePlainNickname 是 GenerateNickname 的同义函数（历史上外站代码用它生成无编号昵称）。
// 昵称不再带编号后两者行为完全一致，保留该名字只为不改动既有调用方。
func GeneratePlainNickname() string { return GenerateNickname() }

// GenerateAvatarSeed 生成 16 字节随机数的十六进制字符串（32 字符）。
func GenerateAvatarSeed() string {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		// crypto/rand 失败极罕见，退化为固定前缀以便调用方仍能工作。
		panic("生成 avatarSeed 失败: " + err.Error())
	}
	return hex.EncodeToString(b)
}

// randIntN 返回 [0, n) 的密码学安全随机整数。
func randIntN(n int) int {
	if n <= 0 {
		return 0
	}
	v, err := rand.Int(rand.Reader, big.NewInt(int64(n)))
	if err != nil {
		return 0
	}
	return int(v.Int64())
}
